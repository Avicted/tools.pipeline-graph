package render

import (
	"fmt"
	"io"
	"regexp"
	"strings"

	"github.com/Avicted/tools.pipeline-graph/internal/model"
)

var reUnsafe = regexp.MustCompile(`[^A-Za-z0-9_]`)

// shortIDs gives every node a stable, syntax-safe identifier.
func shortIDs(g *model.Graph) map[string]string {
	ids := map[string]string{}
	for i, n := range g.Nodes {
		ids[n.ID] = fmt.Sprintf("n%d_%s", i, reUnsafe.ReplaceAllString(n.Label, "_"))
	}
	return ids
}

func groupByLane(g *model.Graph) ([]string, map[string][]*model.Node) {
	lanes := []string{}
	for _, r := range g.Repos {
		lanes = append(lanes, r.Name)
	}
	lanes = append(lanes, ExternalLane)
	by := map[string][]*model.Node{}
	for _, n := range g.Nodes {
		by[laneOf(n)] = append(by[laneOf(n)], n)
	}
	return lanes, by
}

func mermaidText(s string) string {
	s = strings.ReplaceAll(s, `"`, "#quot;")
	return strings.NewReplacer("&", "#amp;", "<", "#lt;", ">", "#gt;").Replace(s)
}

// Mermaid writes a flowchart (renders in GitHub/GitLab markdown, Miro's Mermaid app, mermaid.live).
func Mermaid(w io.Writer, g *model.Graph) error {
	var b strings.Builder
	ids := shortIDs(g)
	b.WriteString("%% Generated by pipeline-graph. " + Subtitle(g) + "\n")
	b.WriteString("flowchart LR\n")
	classes := []struct {
		name string
		s    style
	}{
		{"build", nodeStyles[model.KindBuild]}, {"composite", compositeStyle}, {"ext", nodeStyles[model.KindExternal]},
		{"make", nodeStyles[model.KindMake]}, {"image", nodeStyles[model.KindImage]},
	}
	for _, cl := range classes {
		k, s := cl.name, cl.s
		dash := ""
		if s.Dashed {
			dash = ",stroke-dasharray:5 3"
		}
		fmt.Fprintf(&b, "  classDef %s fill:%s,stroke:%s,color:%s%s\n", k, s.Fill, s.Stroke, s.Text, dash)
	}
	lanes, by := groupByLane(g)
	for i, lane := range lanes {
		nodes := by[lane]
		if len(nodes) == 0 {
			continue
		}
		fmt.Fprintf(&b, "  subgraph lane%d[\"%s\"]\n    direction LR\n", i, mermaidText(lane))
		for _, n := range nodes {
			c := CardOf(n)
			label := "<b>" + mermaidText(c.Title) + "</b>"
			if c.Sub != "" {
				label += "<br/><small>" + mermaidText(c.Sub) + "</small>"
			}
			open, close, class := "[\"", "\"]", "build"
			switch {
			case n.Composite:
				class = "composite"
			case n.Kind == model.KindMake:
				open, close, class = "(\"", "\")", "make"
			case n.Kind == model.KindImage:
				open, close, class = "[(\"", "\")]", "image"
			case n.Kind == model.KindExternal:
				open, close, class = "[/\"", "\"/]", "ext"
			}
			fmt.Fprintf(&b, "    %s%s%s%s:::%s\n", ids[n.ID], open, label, close, class)
		}
		b.WriteString("  end\n")
		fmt.Fprintf(&b, "  style lane%d fill:#F8FAFC,stroke:#CBD5E1\n", i)
	}
	var links []string
	for i, e := range g.Edges {
		arrow := "-->"
		switch edgeStyles[e.Kind].Dash {
		case "dash", "dot":
			arrow = "-.->"
		}
		if e.Kind == model.EdgeTrigger {
			arrow = "==>"
		}
		label := e.Label
		if e.Kind == model.EdgeTrigger {
			label = strings.TrimSpace("triggers " + label)
		}
		if e.Kind == model.EdgeRuns {
			label = ""
		}
		if label != "" {
			fmt.Fprintf(&b, "  %s %s|\"%s\"| %s\n", ids[e.From], arrow, mermaidText(label), ids[e.To])
		} else {
			fmt.Fprintf(&b, "  %s %s %s\n", ids[e.From], arrow, ids[e.To])
		}
		es := edgeStyles[e.Kind]
		links = append(links, fmt.Sprintf("  linkStyle %d stroke:%s,stroke-width:%.1fpx", i, es.Color, es.Width))
	}
	b.WriteString(strings.Join(links, "\n"))
	b.WriteString("\n")
	_, err := io.WriteString(w, b.String())
	return err
}

func dotQuote(s string) string {
	return `"` + strings.NewReplacer(`\`, `\\`, `"`, `\"`, "\n", `\n`).Replace(s) + `"`
}

// DOT writes a Graphviz graph with one cluster per repository.
func DOT(w io.Writer, g *model.Graph) error {
	var b strings.Builder
	ids := shortIDs(g)
	b.WriteString("// Generated by pipeline-graph. " + Subtitle(g) + "\n")
	b.WriteString("digraph pipelines {\n  rankdir=LR; newrank=true; splines=true; nodesep=0.35; ranksep=0.9;\n")
	b.WriteString("  graph [fontname=\"Helvetica\", fontsize=12, labelloc=t, label=" + dotQuote("Pipeline map\n"+Subtitle(g)) + "];\n")
	b.WriteString("  node [fontname=\"Helvetica\", fontsize=10, shape=box, style=\"rounded,filled\", penwidth=1.4];\n")
	b.WriteString("  edge [fontname=\"Helvetica\", fontsize=9, arrowsize=0.7];\n")
	lanes, by := groupByLane(g)
	for i, lane := range lanes {
		nodes := by[lane]
		if len(nodes) == 0 {
			continue
		}
		fmt.Fprintf(&b, "  subgraph cluster_%d {\n    label=%s; style=\"rounded,filled\"; fillcolor=\"#F8FAFC\"; color=\"#CBD5E1\"; fontsize=13;\n", i, dotQuote(lane))
		for _, n := range nodes {
			c := CardOf(n)
			s := nodeStyle(n)
			label := c.Title
			if c.Sub != "" {
				label += "\n" + c.Sub
			}
			for _, l := range c.Lines {
				label += "\n" + l
			}
			if len(c.Badges) > 0 {
				label += "\n" + strings.Join(c.Badges, "  ")
			}
			extra := ""
			if s.Dashed {
				extra = `, style="rounded,filled,dashed"`
			}
			fmt.Fprintf(&b, "    %s [label=%s, fillcolor=%q, color=%q, fontcolor=%q%s];\n", ids[n.ID], dotQuote(label), s.Fill, s.Stroke, s.Text, extra)
		}
		b.WriteString("  }\n")
	}
	for _, e := range g.Edges {
		es := edgeStyles[e.Kind]
		st := "solid"
		switch es.Dash {
		case "dash":
			st = "dashed"
		case "dot":
			st = "dotted"
		}
		label := e.Label
		if e.Kind == model.EdgeTrigger {
			label = strings.TrimSpace("triggers " + label)
		}
		if e.Kind == model.EdgeRuns {
			label = ""
		}
		fmt.Fprintf(&b, "  %s -> %s [color=%q, penwidth=%.1f, style=%s, label=%s];\n", ids[e.From], ids[e.To], es.Color, es.Width, st, dotQuote(label))
	}
	b.WriteString("}\n")
	_, err := io.WriteString(w, b.String())
	return err
}
